const normalize = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

export function searchPlaces(query: string, limit = 8): Place[] {
  const q = normalize(query);
  if (!q) return [];
  const starts: Place[] = [];
  const includes: Place[] = [];
  for (const p of PLACES) {
    const n = normalize(p.name);
    if (n.startsWith(q)) starts.push(p);
    else if (n.includes(q)) includes.push(p);
    if (starts.length >= limit) break;
  }
  return [...starts, ...includes].slice(0, limit);
}

export function findPlace(name: string): Place | null {
  const target = normalize(name);
  if (!target) return null;
  // Exact normalized match first
  for (const p of PLACES) if (normalize(p.name) === target) return p;
  // Then "city name" prefix match (e.g. user typed "Mumbai")
  for (const p of PLACES) {
    const city = normalize(p.name.split(",")[0]);
    if (city === target) return p;
  }
  // Fallback to includes
  for (const p of PLACES) if (normalize(p.name).includes(target)) return p;
  return null;
}